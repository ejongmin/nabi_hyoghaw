def set_font(run, name='맑은 고딕', size=None, bold=False, color=None, italic=False):
    run.font.name = name
    run._element.rPr.rFonts.set(qn('w:eastAsia'), name)
    if size:  run.font.size = Pt(size)
    if bold:  run.font.bold = True
    if italic: run.font.italic = True
    if color: run.font.color.rgb = RGBColor(*color)


def add_title(text, level=1):
    p = doc.add_heading(text, level=level)
    for run in p.runs:
        run.font.name = '맑은 고딕'
        run._element.rPr.rFonts.set(qn('w:eastAsia'), '맑은 고딕')
    return p


def add_para(text='', indent=0, bold=False, color=None, size=10.5):
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.left_indent = Inches(indent * 0.3)
    run = p.add_run(text)
    set_font(run, size=size, bold=bold, color=color)
    return p


def add_box(label, color_rgb, content_lines):
    """색상 라벨 박스."""
    table = doc.add_table(rows=1, cols=1)
    table.style = 'Table Grid'
    cell = table.cell(0, 0)
    cell.width = Inches(6.0)

    # 라벨 줄
    p_label = cell.paragraphs[0]
    p_label.paragraph_format.space_before = Pt(4)
    run_label = p_label.add_run(f"  {label}")
    set_font(run_label, size=9, bold=True, color=color_rgb)

    # 내용 줄들
    for line in content_lines:
        p = cell.add_paragraph()
        p.paragraph_format.left_indent = Inches(0.15)
        run = p.add_run(line)
        set_font(run, size=10)

    # 셀 배경색 (연하게)
    shading = OxmlElement('w:shd')
    bg = 'F8FAFF' if color_rgb == (37, 99, 235) else \
         'FFF8F0' if color_rgb == (245, 158, 11) else \
         'F0FFF4' if color_rgb == (22, 163, 74) else \
         'FFF0F0'
    shading.set(qn('w:fill'), bg)
    shading.set(qn('w:color'), 'auto')
    shading.set(qn('w:val'), 'clear')
    cell._tc.get_or_add_tcPr().append(shading)
    doc.add_paragraph()  # 박스 아래 여백


def slide_section(num, title, subtitle):
    """슬라이드 섹션 헤더."""
    doc.add_page_break()
    # 슬라이드 번호 + 제목
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(0)
    r1 = p.add_run(f"SLIDE {num:02d}  ")
    set_font(r1, size=9, color=(100, 100, 100))
    r2 = p.add_run(f"{title}")
    set_font(r2, size=15, bold=True, color=(30, 58, 95))
    if subtitle:
        p2 = doc.add_paragraph()
        r3 = p2.add_run(f"  {subtitle}")
        set_font(r3, size=10, italic=True, color=(107, 114, 128))

    # 구분선
    p_line = doc.add_paragraph()
    p_line.paragraph_format.space_before = Pt(2)
    p_line.paragraph_format.space_after = Pt(6)
    r_line = p_line.add_run("─" * 60)
    set_font(r_line, size=8, color=(200, 200, 200))


